package preference

import (
	"context"
	"errors"
	"time"

	"github.com/google/uuid"
)

type Pace string

const (
	PaceRelaxed  Pace = "relaxed"
	PaceBalanced Pace = "balanced"
	PacePacked   Pace = "packed"
)

func (p Pace) Valid() bool {
	switch p {
	case "", PaceRelaxed, PaceBalanced, PacePacked:
		return true
	}
	return false
}

type DateFlexibility string

const (
	DateFixed      DateFlexibility = "fixed"
	DatePlusMinus2 DateFlexibility = "plus_minus_2"
	DateFlexible   DateFlexibility = "flexible"
)

func (d DateFlexibility) Valid() bool {
	switch d {
	case "", DateFixed, DatePlusMinus2, DateFlexible:
		return true
	}
	return false
}

var (
	ErrNegativeBudget  = errors.New("preference: budget must not be negative")
	ErrInvalidPace     = errors.New("preference: invalid pace")
	ErrInvalidFlex     = errors.New("preference: invalid date_flexibility")
	ErrInvalidTimeSpan = errors.New("preference: latest_end_time must be after earliest_start_time")
	ErrNotFound        = errors.New("preference: not found")
)

// Preference captures one member's stated constraints/wants for a trip. It
// is retrieved-and-grounded context for the AI planner — never generated by
// the LLM, only ever supplied to it.
type Preference struct {
	ID                uuid.UUID
	TripID            uuid.UUID
	UserID            uuid.UUID
	BudgetPaise       *int64
	Pace              Pace
	Interests         []string
	Dietary           []string
	MobilityNotes     *string
	EarliestStartTime *string // "HH:MM", 24h
	LatestEndTime     *string
	DateFlexibility   DateFlexibility
	Notes             *string
	CreatedAt         time.Time
	UpdatedAt         time.Time
}

type UpsertInput struct {
	TripID            uuid.UUID
	UserID            uuid.UUID
	BudgetPaise       *int64
	Pace              Pace
	Interests         []string
	Dietary           []string
	MobilityNotes     *string
	EarliestStartTime *string
	LatestEndTime     *string
	DateFlexibility   DateFlexibility
	Notes             *string
}

func New(in UpsertInput) (*Preference, error) {
	if in.BudgetPaise != nil && *in.BudgetPaise < 0 {
		return nil, ErrNegativeBudget
	}
	if !in.Pace.Valid() {
		return nil, ErrInvalidPace
	}
	if !in.DateFlexibility.Valid() {
		return nil, ErrInvalidFlex
	}
	if in.EarliestStartTime != nil && in.LatestEndTime != nil {
		if *in.LatestEndTime <= *in.EarliestStartTime {
			return nil, ErrInvalidTimeSpan
		}
	}
	now := time.Now().UTC()
	return &Preference{
		ID:                uuid.New(),
		TripID:            in.TripID,
		UserID:            in.UserID,
		BudgetPaise:       in.BudgetPaise,
		Pace:              in.Pace,
		Interests:         in.Interests,
		Dietary:           in.Dietary,
		MobilityNotes:     in.MobilityNotes,
		EarliestStartTime: in.EarliestStartTime,
		LatestEndTime:     in.LatestEndTime,
		DateFlexibility:   in.DateFlexibility,
		Notes:             in.Notes,
		CreatedAt:         now,
		UpdatedAt:         now,
	}, nil
}

type Repository interface {
	Upsert(ctx context.Context, p *Preference) error
	GetByTripAndUser(ctx context.Context, tripID, userID uuid.UUID) (*Preference, error)
	ListByTrip(ctx context.Context, tripID uuid.UUID) ([]*Preference, error)
}
